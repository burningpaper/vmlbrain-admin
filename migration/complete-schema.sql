CREATE EXTENSION IF NOT EXISTS vector;

-- ============================================
-- 2. Create Tables
-- ============================================

-- Sections table (for homepage organization)
CREATE TABLE IF NOT EXISTS sections (
  key TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  icon TEXT NULL,
  image_name TEXT NULL,
  sort_order INTEGER DEFAULT 0
);

-- Policies table (main knowledge base articles)
-- Note: Using UUID to match Supabase schema
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

CREATE TABLE IF NOT EXISTS policies (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  slug TEXT UNIQUE NOT NULL,
  title TEXT NOT NULL,
  summary TEXT,
  body_md TEXT,
  parent_slug TEXT,
  section_key TEXT NULL REFERENCES sections(key),
  box_folder_id TEXT NULL,
  box_file_ids TEXT[] NULL,
  audience TEXT[] DEFAULT ARRAY['All'],
  status TEXT DEFAULT 'approved',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  FOREIGN KEY (parent_slug) REFERENCES policies(slug) ON DELETE SET NULL
);

-- Profiles table (people directory)
CREATE TABLE IF NOT EXISTS profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  first_name TEXT NOT NULL,
  last_name TEXT NOT NULL,
  job_title TEXT NOT NULL,
  description_html TEXT NOT NULL,
  clients TEXT[] DEFAULT '{}'::TEXT[],
  experience TEXT,
  photo_url TEXT,
  email TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'approved' CHECK (status IN ('approved','draft')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Policy embeddings table (for AI chatbot)
CREATE TABLE IF NOT EXISTS policy_embeddings (
  id BIGSERIAL PRIMARY KEY,
  policy_id UUID REFERENCES policies(id) ON DELETE CASCADE,
  policy_slug TEXT NOT NULL,
  chunk_index INT NOT NULL,
  content TEXT NOT NULL,
  embedding vector(1536), -- OpenAI ada-002 embedding size
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(policy_slug, chunk_index)
);

-- Profile embeddings table (for AI chatbot)
CREATE TABLE IF NOT EXISTS profile_embeddings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id BIGINT NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  profile_slug TEXT NOT NULL,
  chunk_index INT NOT NULL,
  content TEXT NOT NULL,
  embedding vector(1536) NOT NULL
);

-- ============================================
-- 3. Create Indexes
-- ============================================

-- Policy embeddings indexes
CREATE INDEX IF NOT EXISTS policy_embeddings_embedding_idx
  ON policy_embeddings
  USING ivfflat (embedding vector_cosine_ops)
  WITH (lists = 100);

CREATE INDEX IF NOT EXISTS policy_embeddings_policy_slug_idx
  ON policy_embeddings(policy_slug);

-- Profile embeddings indexes
CREATE INDEX IF NOT EXISTS profile_embeddings_slug_idx
  ON profile_embeddings (profile_slug);

