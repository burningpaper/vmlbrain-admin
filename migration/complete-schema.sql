-- Function to search policy embeddings
CREATE OR REPLACE FUNCTION match_policy_embeddings(
  query_embedding vector(1536),
  match_threshold float DEFAULT 0.7,
  match_count int DEFAULT 5
)
RETURNS TABLE (
  id bigint,
  policy_slug text,
  chunk_index int,
  content text,
  similarity float
)
LANGUAGE sql STABLE
AS $$
  SELECT
    policy_embeddings.id,
    policy_embeddings.policy_slug,
    policy_embeddings.chunk_index,
    policy_embeddings.content,
    1 - (policy_embeddings.embedding <=> query_embedding) as similarity
  FROM policy_embeddings
  WHERE 1 - (policy_embeddings.embedding <=> query_embedding) > match_threshold
  ORDER BY policy_embeddings.embedding <=> query_embedding
  LIMIT match_count;
$$;

-- Function to search profile embeddings
CREATE OR REPLACE FUNCTION match_profile_embeddings (
  query_embedding vector(1536),
  match_threshold float,
  match_count int
) RETURNS TABLE (
  id bigint,
  profile_slug text,
  content text,
  chunk_index int,
  similarity float
)
LANGUAGE plpgsql
AS $$
BEGIN
  RETURN QUERY
  SELECT
    pe.id,
    pe.profile_slug,
    pe.content,
    pe.chunk_index,
    1 - (pe.embedding <-> query_embedding) as similarity
  FROM profile_embeddings pe
  WHERE 1 - (pe.embedding <-> query_embedding) >= match_threshold
  ORDER BY pe.embedding <-> query_embedding
  LIMIT match_count;
END;
$$;

